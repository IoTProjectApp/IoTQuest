// Metre-scale animal silhouettes, with curved bodies and small identifying details.
// x points forward; ears/eyes sit on both sides. Optional transforms are preserved by pose().
const eyes = (x, y, z, r = 0.025) =>
  [-1, 1].map((side) => ['sphere', [x, y, side * z], [r * 2, r * 2, r * 2], '#252f2b', 'head']);
const ears = (x, y, z, length = 0.23) =>
  [-1, 1].map((side) => [
    'sphere',
    [x, y, side * z],
    [length, 0.09, 0.075],
    'coat',
    'head',
    { rotation: [side * 0.2, 0, side * 0.15] },
  ]);
const legs = (x, z, height, radius, color = 'coat') =>
  [-1, 1].flatMap((front) =>
    [-1, 1].flatMap((side) => [
      [
        'cylinder',
        [front * x, height * 0.75, side * z],
        [radius * 2, height * 0.5, radius * 2],
        color,
        'leg',
      ],
      [
        'cylinder',
        [front * x, height * 0.26, side * z],
        [radius * 1.45, height * 0.49, radius * 1.45],
        color,
        'leg',
      ],
      [
        'sphere',
        [front * x + 0.025, 0.045, side * z],
        [radius * 2.2, 0.09, radius * 2.1],
        '#424238',
        'hoof',
      ],
    ]),
  );
const shadow = (w, d) => [
  'sphere',
  [0, 0.012, 0],
  [w, 0.012, d],
  '#3a483d',
  'shadow',
  { opacity: 0.12 },
];

